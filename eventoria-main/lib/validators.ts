/**
 * @file lib/validators.ts
 * Zod validation schemas for all incoming API requests and AI-generated outputs.
 */

import { z } from "zod";
import { LIMITS } from "./constants";

/** Schema for user-submitted event planning requests */
export const eventPlanRequestSchema = z
  .object({
    eventType: z.enum(["wedding", "birthday", "community"] as const, {
      message: "Event type must be either 'wedding', 'birthday', or 'community'",
    }),
    guestCount: z
      .number({ message: "Guest count must be a number" })
      .int("Guest count must be an integer")
      .min(LIMITS.MIN_GUESTS, `Guest count must be at least ${LIMITS.MIN_GUESTS}`)
      .max(LIMITS.MAX_GUESTS, `Guest count cannot exceed ${LIMITS.MAX_GUESTS}`),
    budget: z
      .number({ message: "Budget must be a number" })
      .min(LIMITS.MIN_BUDGET, `Budget must be at least INR ${LIMITS.MIN_BUDGET}`)
      .max(LIMITS.MAX_BUDGET, `Budget cannot exceed INR ${LIMITS.MAX_BUDGET}`),
    date: z
      .string({ message: "Date must be a string" })
      .min(1, "Event date is required")
      .refine(
        (val) => !isNaN(new Date(val).getTime()),
        "Event date must be a valid parseable date"
      ),
    city: z
      .string({ message: "City must be a string" })
      .trim()
      .min(2, "City must be at least 2 characters")
      .max(100, "City cannot exceed 100 characters"),
    description: z
      .string({ message: "Description must be a string" })
      .trim()
      .max(LIMITS.MAX_DESCRIPTION_LENGTH, `Description cannot exceed ${LIMITS.MAX_DESCRIPTION_LENGTH} characters`)
      .default(""),
    preferences: z
      .array(
        z
          .string()
          .trim()
          .max(LIMITS.MAX_PREFERENCE_LENGTH, `Preference item cannot exceed ${LIMITS.MAX_PREFERENCE_LENGTH} chars`)
      )
      .max(LIMITS.MAX_PREFERENCES, `Cannot provide more than ${LIMITS.MAX_PREFERENCES} preferences`)
      .default([]),
  })
  .strict();

export type ValidatedEventPlanRequest = z.infer<typeof eventPlanRequestSchema>;

/** Schema for individual budget items generated by AI */
export const budgetItemSchema = z
  .object({
    category: z.string().min(1),
    estimatedCost: z.number().nonnegative(),
    percentOfTotal: z.number().min(0).max(100),
    notes: z.string().default(""),
    priority: z.enum(["essential", "recommended", "optional"]).default("recommended"),
    savingTips: z.array(z.string()).default([]),
  })
  .strict();

/** Schema for timeline items generated by AI */
export const timelineItemSchema = z
  .object({
    title: z.string().min(1),
    description: z.string().default(""),
    phase: z.string().min(1),
    daysBeforeEvent: z.number().int().nonnegative(),
    category: z.string().min(1),
    priority: z.enum(["high", "medium", "low"]).default("medium"),
  })
  .strict();

/** Schema for vendor checklist items generated by AI */
export const vendorChecklistItemSchema = z
  .object({
    category: z.string().min(1),
    priorityTier: z.enum(["must-have", "should-have", "nice-to-have"]).default("must-have"),
    itemsToBook: z.array(z.string()).default([]),
    questionsToAsk: z.array(z.string()).default([]),
    contractChecks: z.array(z.string()).default([]),
    tips: z.array(z.string()).default([]),
    estimateLowPercent: z.number().min(0).max(100).default(0),
    estimateHighPercent: z.number().min(0).max(100).default(0),
    bookByDaysBefore: z.number().int().nonnegative().default(30),
  })
  .strict();

/** Schema for personalized ideas generated by AI */
export const personalizedIdeaSchema = z
  .object({
    title: z.string().min(1),
    description: z.string().default(""),
    category: z.string().min(1),
    tier: z.enum(["diy", "standard", "premium"]).default("standard"),
    estimatedCost: z.number().nonnegative().default(0),
  })
  .strict();

/** Schema for full EventPlan output from AI */
export const eventPlanSchema = z
  .object({
    summary: z.string().min(1),
    eventType: z.enum(["wedding", "birthday", "community"]),
    budgetBreakdown: z.array(budgetItemSchema).min(1),
    timeline: z.array(timelineItemSchema).min(1),
    vendorChecklist: z.array(vendorChecklistItemSchema).min(1),
    personalizedIdeas: z.array(personalizedIdeaSchema).min(1),
    tips: z.array(z.string()).default([]),
  })
  .strict();

export type ValidatedEventPlan = z.infer<typeof eventPlanSchema>;

/** Schema for Chat Message */
export const chatMessageSchema = z
  .object({
    id: z.string().default(() => Math.random().toString(36).substring(2, 9)),
    role: z.enum(["user", "assistant", "system"]),
    content: z
      .string()
      .trim()
      .min(1, "Message content cannot be empty")
      .max(LIMITS.MAX_CHAT_INPUT_LENGTH, `Message cannot exceed ${LIMITS.MAX_CHAT_INPUT_LENGTH} chars`),
    timestamp: z.number().default(() => Date.now()),
    modelTier: z.enum(["quick", "detailed"]).optional(),
  })
  .strict();

/** Schema for streaming chat request */
export const chatRequestSchema = z
  .object({
    messages: z
      .array(chatMessageSchema)
      .min(1, "At least one message is required")
      .max(10, "Cannot send more than 10 messages per request"),
    eventContext: eventPlanRequestSchema.partial().optional(),
  })
  .strict();

export type ValidatedChatRequest = z.infer<typeof chatRequestSchema>;

/** Schema for non-streaming quick ask request */
export const askRequestSchema = z
  .object({
    question: z
      .string()
      .trim()
      .min(1, "Question cannot be empty")
      .max(LIMITS.MAX_CHAT_INPUT_LENGTH, `Question cannot exceed ${LIMITS.MAX_CHAT_INPUT_LENGTH} chars`),
    eventContext: eventPlanRequestSchema.partial().optional(),
  })
  .strict();

export type ValidatedAskRequest = z.infer<typeof askRequestSchema>;
